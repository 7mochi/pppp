CLAMPED = {
    ("DT", "speed_change"), ("NC", "speed_change"), ("HT", "speed_change"), ("DC", "speed_change"),
    ("AS", "initial_rate"),
    ("RD", "angle_sharpness"),
    ("MG", "attraction_strength"),
    ("GR", "start_scale"), ("DF", "start_scale"),
}


def set_body(kind, target):
    if kind == "double":
        return "%s = std::atof(value);" % target
    if kind in ("float", "optional_float"):
        return "%s = static_cast<float>(std::atof(value));" % target
    if kind == "int":
        return "%s = std::atoi(value);" % target
    if kind == "bool":
        return "{ bool b; if (utils::parse_bool(value, &b)) { return -1; } %s = b; }" % target
    if kind == "reflection":
        return None
    raise SystemExit("unknown kind %r" % kind)


def ignore_body(kind):
    if kind == "boolean":
        return "{ bool b; return utils::parse_bool(value, &b); }"
    return "return value != 0 && value[0] != 0 ? 0 : -1;"


def literal(value, suffix):
    return repr(float(value)) + suffix


def clamp_body(target, kind, setting):
    suffix = "f" if kind == "float" else ""
    return "clamp_and_round(&%s, %s, %s, %s, %s);" % (
        target, target,
        literal(setting["min"], suffix), literal(setting["max"], suffix),
        literal(setting["precision"], suffix),
    )


def mod_order_from_header():
    text = MOD_HEADER.read_text(encoding="utf-8")
    block = re.search(r"enum ModId \{(.*?)\n\s*MOD_COUNT", text, re.S)
    if not block:
        raise SystemExit("could not find the ModId enum in %s" % MOD_HEADER)
    order = re.findall(r"\bMOD_([A-Za-z0-9]+)\b", block.group(1))
    if not order:
        raise SystemExit("the ModId enum in %s is empty" % MOD_HEADER)
    return order


def reference_pin():
    text = REFERENCE_CSPROJ.read_text(encoding="utf-8")
    match = re.search(r'Include="ppy\.osu\.Game" Version="([^"]+)"', text)
    if not match:
        raise SystemExit("could not find the ppy.osu.Game pin in %s" % REFERENCE_CSPROJ)
    return match.group(1)


def build_model(mods_json):
    order = mod_order_from_header()

    if sorted(mod["acronym"] for mod in mods_json) != sorted(order):
        raise SystemExit("the mods data does not match the ModId enum in %s" % MOD_HEADER)

    by_acronym = {mod["acronym"]: mod for mod in mods_json}
    mods = []

    for acronym in order:
        mod = by_acronym[acronym]
        keys = {setting["key"]: setting for setting in mod["settings"]}
        family = FAMILY.get(acronym, "none")

        stored = []
        clamps = []
        for key, (field, kind) in sorted(STORED.get(acronym, {}).items()):
            if key not in keys:
                raise SystemExit("%s: stored key %r missing from the data" % (acronym, key))
            target = "mod_%s(*mod).%s" % (family, field)
            stored.append({"key": key, "target": target, "kind": kind, "set": set_body(kind, target)})
            if (acronym, key) in CLAMPED:
                clamps.append({"clamp": clamp_body(target, kind, keys[key])})

        ignored_keys = sorted(key for key in keys if key not in STORED.get(acronym, {}))
        if ignored_keys != sorted(IGNORED.get(acronym, [])):
            raise SystemExit("%s: expected ignored %r, found %r"
                             % (acronym, sorted(IGNORED.get(acronym, [])), ignored_keys))

        ignored = [{"key": key, "ignore": ignore_body(keys[key]["type"])} for key in ignored_keys]

        rulesets = 0
        for index, name in enumerate(("osu", "taiko", "catch", "mania")):
            if name in mod["rulesets"]:
                rulesets |= 1 << index

        mods.append({
            "acronym": acronym,
            "name": mod["name"],
            "rulesets": rulesets,
            "incompatible": mod["incompatible"],
            "legacy": mod["legacy"],
            "stored": stored,
            "ignored": ignored,
            "clamped": clamps,
        })

    return mods


def main():
    banner = BANNER % reference_pin()
    models = build_model(json.loads(MODS_JSON.read_text(encoding="utf-8")))

    header = ENVIRONMENT.get_template("generated_mods.h.j2").render(banner=banner)
    source = ENVIRONMENT.get_template("generated_mods.cpp.j2").render(banner=banner, models=models)

    HEADER_PATH.write_text(header, encoding="utf-8")
    SOURCE_PATH.write_text(source, encoding="utf-8")

    print("wrote %s and %s (%d mods)" % (HEADER_PATH.name, SOURCE_PATH.name, len(models)))


if __name__ == "__main__":
    main()
