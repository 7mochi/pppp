def reference_version():
    root = ElementTree.parse(REFERENCE_CSPROJ).getroot()
    pins = {package.get("Include"): package.get("Version")
            for package in root.iter("PackageReference")}
    if len(set(pins.values())) != 1:
        raise SystemExit("upstream.csproj doesn't pin one version: %r" % pins)
    return next(iter(pins.values()))


def dotnet(arguments):
    command = ["dotnet"] + arguments
    if not os.environ.get("IN_NIX_SHELL"):
        command = ["nix", "develop", "--command"] + command
    return subprocess.run(
        command,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        universal_newlines=True,
        check=True,
    ).stdout


_built = False


def run_reference(rows_path):
    global _built
    if not _built:
        dotnet(["build", "-c", "Release", REFERENCE])
        _built = True

    descriptor, expected_path = tempfile.mkstemp(suffix=".json")
    os.close(descriptor)
    try:
        dotnet([REFERENCE_DLL, rows_path, RESOURCES, expected_path])
        with open(expected_path) as expected_file:
            return json.load(expected_file)
    finally:
        os.unlink(expected_path)


def cpp_float(value):
    return repr(float(value))


def cpp_double(value):
    text = repr(float(value))
    return text[:-2] if text.endswith(".0") else text


def write_guard(out, out_path):
    guard = "PPPP_TESTS_PARITY_" + os.path.basename(out_path).replace(".h", "").upper() + "_H"
    out.write("\n#ifndef " + guard + "\n#define " + guard + "\n\n")
    return guard


def write_header(out, rows):
    out.write(HEADER.format(
        version=reference_version(), date=datetime.date.today().isoformat()))


def emit_decode(rows):
    with open(DECODE_HEADER, "w") as out:
        write_header(out, len(rows))
        write_guard(out, DECODE_HEADER)
        out.write("namespace parity {\n")
        out.write("struct DecodeRow {\n"
                  "    const char* map;\n"
                  "    int format;\n"
                  "    int mode;\n"
                  "    float ar;\n"
                  "    float od;\n"
                  "    float cs;\n"
                  "    float hp;\n"
                  "    float slider_multiplier;\n"
                  "    float slider_tick_rate;\n"
                  "    int hit_objects;\n"
                  "    int uninherited_points;\n"
                  "    int breaks;\n"
                  "    float stack_leniency;\n"
                  "};\n\n")
        out.write("static const DecodeRow decode_rows[] = {\n")
        for row in rows:
            fields = row["decode"]
            out.write('    {"%s", %s, %s, %sf, %sf, %sf, %sf, %sf, %sf, %s, %s, %s, %sf},\n' % (
                row["map"], fields["format"], fields["mode"], cpp_float(fields["ar"]),
                cpp_float(fields["od"]), cpp_float(fields["cs"]), cpp_float(fields["hp"]),
                cpp_float(fields["slider_multiplier"]), cpp_float(fields["slider_tick_rate"]),
                fields["hit_objects"], fields["uninherited_points"], fields["breaks"],
                cpp_float(fields["stack_leniency"])))
        out.write("};\n\n}")
        out.write(" // namespace parity\n")
        out.write("\n#endif\n")


def emit_difficulty(by_mode):
    with open(DIFFICULTY_HEADER, "w") as out:
        write_header(out, sum(len(rows) for rows in by_mode.values()))
        write_guard(out, DIFFICULTY_HEADER)
        out.write("namespace parity {")
        for mode, fields in DIFFICULTY_FIELDS.items():
            out.write("\nstruct " + mode.title() + "DiffRow {\n"
                      "    const char* name;\n"
                      "    const char* map;\n"
                      "    const char* mods;\n")
            for name, ctype in fields:
                out.write("    %s %s;\n" % (ctype, name))
            out.write("};\n\n")
            out.write("static const " + mode.title() + "DiffRow " + mode + "_diff_rows[] = {\n")
            for row in by_mode.get(mode, []):
                values = ["\"%s\"" % row["case"], "\"/%s\"" % row["map"].lstrip("/"),
                          "\"%s\"" % ",".join(row["mods"])]
                for name, ctype in fields:
                    value = row["difficulty"][name]
                    if ctype == "float":
                        values.append(cpp_float(value) + "f")
                    else:
                        values.append(str(value))
                out.write("    {%s},\n" % ", ".join(values))
            out.write("};\n")
        out.write("\n}")
        out.write(" // namespace parity\n")
        out.write("\n#endif\n")


def score_value(row, key):
    value = row["score"].get(key)
    if value is not None:
        return str(value)
    return "-1" if key == "accuracy" else "0"


def emit_performance(by_mode):
    with open(PERFORMANCE_HEADER, "w") as out:
        write_header(out, sum(len(rows) for rows in by_mode.values()))
        write_guard(out, PERFORMANCE_HEADER)
        
        out.write("#include <limits>\n\n")
        out.write("namespace parity {")
        for mode, fields in PERFORMANCE_FIELDS.items():
            out.write("\nstruct " + mode.title() + "PpRow {\n"
                      "    const char* name;\n"
                      "    const char* map;\n"
                      "    const char* mods;\n"
                      "    const char* score;\n")
            for name, _key, ctype in SCORE_FIELDS[mode]:
                out.write("    %s %s;\n" % (ctype, name))
            for name, _member in fields:
                out.write("    double %s;\n" % name)
            out.write("};\n\n")
            out.write("static const " + mode.title() + "PpRow " + mode + "_pp_rows[] = {\n")
            for row in by_mode.get(mode, []):
                values = ["\"%s\"" % row["case"], "\"/%s\"" % row["map"].lstrip("/"),
                          "\"%s\"" % ",".join(row["mods"]),
                          "\"%s\"" % ",".join("%s=%s" % (key, value)
                                              for key, value in row["score"].items())]
                for name, key, ctype in SCORE_FIELDS[mode]:
                    value = score_value(row, key)
                    if ctype == "int":
                        values.append(value.split(".")[0])
                    elif ctype == "double":
                        values.append(value)
                    else:
                        values.append(cpp_float(value) + "f")
                for _name, member in fields:
                    value = row["performance"].get(member)
                    values.append("std::numeric_limits<double>::quiet_NaN()" if value is None
                                  else cpp_double(value))
                out.write("    {%s},\n" % ", ".join(values))
            out.write("};\n")
        out.write("\n}")
        out.write(" // namespace parity\n")
        out.write("\n#endif\n")


def main():
    rows = run_reference(ROWS)

    by_mode = {}
    scored_by_mode = {}
    for row in rows:
        mode = MODE_NAMES[row["ruleset"]]
        by_mode.setdefault(mode, []).append(row)
        if "performance" in row:
            scored_by_mode.setdefault(mode, []).append(row)

    emit_decode(rows)
    emit_difficulty(by_mode)
    emit_performance(scored_by_mode)


if __name__ == "__main__":
    main()
